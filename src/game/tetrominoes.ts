export function shuffleBag(): PieceType[] {
  const bag = [...PIECE_TYPES];
  for (let i = bag.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    const swap = bag[i];
    const other = bag[j];
    if (swap === undefined || other === undefined) continue;
    bag[i] = other;
    bag[j] = swap;
  }
  return bag;
}
